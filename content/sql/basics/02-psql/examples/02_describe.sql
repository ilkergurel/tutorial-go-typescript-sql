CREATE TABLE orders (
  id         int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email      varchar(80) NOT NULL,
  total      numeric(10,2) NOT NULL CHECK (total >= 0),
  tags       text[] NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);

-- \d orders, top half: columns with psql's type names and defaults.
SELECT a.attname AS "Column",
       format_type(a.atttypid, a.atttypmod) AS "Type",
       CASE WHEN a.attnotnull THEN 'not null' ELSE '' END AS "Nullable",
       CASE a.attidentity
         WHEN 'a' THEN 'generated always as identity'
         WHEN 'd' THEN 'generated by default as identity'
         ELSE pg_get_expr(d.adbin, d.adrelid)
       END AS "Default"
FROM pg_attribute a
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = 'orders'::regclass
  AND a.attnum > 0 AND NOT a.attisdropped   -- skip system and dropped columns
ORDER BY a.attnum;

-- \d orders, bottom half: constraints. contype 'n' rows are the NOT NULLs,
-- which PG 18 stores here too; the query above already shows them.
SELECT conname, pg_get_constraintdef(oid) AS definition
FROM pg_constraint
WHERE conrelid = 'orders'::regclass AND contype <> 'n'
ORDER BY conname;

-- The SQL-standard, portable view of the same columns: no modifiers in
-- data_type, and anything Postgres-specific is just 'ARRAY' or 'USER-DEFINED'.
SELECT column_name, data_type, is_nullable
FROM information_schema.columns
WHERE table_schema = current_schema() AND table_name = 'orders'
ORDER BY ordinal_position;
